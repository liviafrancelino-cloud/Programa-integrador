-- ============================================================
-- PROJETO INTEGRADOR
-- SISTEMA DE PROGRAMAÇÃO DE PRODUÇÃO E MONTAGEM DE CARGAS
-- Banco de Dados: PostgreSQL / Supabase
-- ============================================================


-- ============================================================
-- 1. TABELA CARGA
-- ============================================================

CREATE TABLE IF NOT EXISTS CARGA (
    id_carga INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_montagem DATE NOT NULL,
    data_entrega_prevista DATE NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    peso_total DECIMAL(10,2) NOT NULL DEFAULT 0,
    capacidade_veiculo DECIMAL(10,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Planejada',

    CONSTRAINT chk_carga_peso
        CHECK (peso_total >= 0),

    CONSTRAINT chk_carga_capacidade
        CHECK (capacidade_veiculo > 0)
);


-- ============================================================
-- 2. TABELA MAQUINA
-- ============================================================

CREATE TABLE IF NOT EXISTS MAQUINA (
    id_maquina INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_maquina VARCHAR(100) NOT NULL,
    tipo_maquina VARCHAR(50) NOT NULL,
    capacidade_horas DECIMAL(10,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Disponível',

    CONSTRAINT chk_maquina_capacidade
        CHECK (capacidade_horas > 0)
);


-- ============================================================
-- 3. TABELA COR
-- ============================================================

CREATE TABLE IF NOT EXISTS COR (
    id_cor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_cor VARCHAR(50) NOT NULL,
    grupo_cor VARCHAR(50) NOT NULL,
    ordem_sequenciamento INTEGER NOT NULL,
    tipo_lavagem VARCHAR(50) NOT NULL,

    CONSTRAINT uq_cor_nome
        UNIQUE (nome_cor),

    CONSTRAINT chk_cor_ordem
        CHECK (ordem_sequenciamento > 0)
);


-- ============================================================
-- 4. TABELA USUARIO
-- ============================================================

CREATE TABLE IF NOT EXISTS USUARIO (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    login VARCHAR(50) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    perfil VARCHAR(30) NOT NULL,

    CONSTRAINT uq_usuario_login
        UNIQUE (login),

    CONSTRAINT chk_usuario_perfil
        CHECK (perfil IN ('PCP/Gestor', 'Operador'))
);


-- ============================================================
-- 5. TABELA ORDEM_FABRICACAO
-- ============================================================

CREATE TABLE IF NOT EXISTS ORDEM_FABRICACAO (
    id_of INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_destino VARCHAR(100) NOT NULL,
    cidade VARCHAR(100) NOT NULL,
    data_entrega DATE NOT NULL,
    peso DECIMAL(10,2) NOT NULL,
    medida VARCHAR(50) NOT NULL,
    tipo_of VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Pendente',
    id_carga INTEGER,

    CONSTRAINT chk_of_peso
        CHECK (peso > 0),

    CONSTRAINT chk_of_tipo
        CHECK (tipo_of IN ('Específica', 'Compartilhada')),

    CONSTRAINT fk_of_carga
        FOREIGN KEY (id_carga)
        REFERENCES CARGA(id_carga)
);


-- ============================================================
-- 6. TABELA PARADA_MAQUINA
-- ============================================================

CREATE TABLE IF NOT EXISTS PARADA_MAQUINA (
    id_parada INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_inicio TIMESTAMP NOT NULL,
    data_fim TIMESTAMP,
    motivo VARCHAR(100) NOT NULL,
    observacao TEXT,

    CONSTRAINT chk_parada_datas
        CHECK (data_fim IS NULL OR data_fim >= data_inicio)
);


-- ============================================================
-- 7. TABELA LOTE_PRODUCAO
-- ============================================================

CREATE TABLE IF NOT EXISTS LOTE_PRODUCAO (
    id_lote INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_lote VARCHAR(50) NOT NULL,
    quantidade INTEGER NOT NULL,
    data_inicio TIMESTAMP,
    data_fim TIMESTAMP,
    status VARCHAR(30) NOT NULL DEFAULT 'Aberto',

    CONSTRAINT uq_lote_numero
        UNIQUE (numero_lote),

    CONSTRAINT chk_lote_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT chk_lote_datas
        CHECK (data_fim IS NULL OR data_inicio IS NULL OR data_fim >= data_inicio)
);


-- ============================================================
-- 8. TABELA MATERIA_PRIMA
-- ============================================================

CREATE TABLE IF NOT EXISTS MATERIA_PRIMA (
    id_material INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_material VARCHAR(100) NOT NULL,
    quantidade_estoque DECIMAL(10,2) NOT NULL DEFAULT 0,
    estoque_minimo DECIMAL(10,2) NOT NULL DEFAULT 0,
    unidade_medida VARCHAR(20) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Normal',

    CONSTRAINT chk_material_estoque
        CHECK (quantidade_estoque >= 0),

    CONSTRAINT chk_material_minimo
        CHECK (estoque_minimo >= 0)
);


-- ============================================================
-- 9. TABELA CHECAGEM_QUALIDADE
-- ============================================================

CREATE TABLE IF NOT EXISTS CHECAGEM_QUALIDADE (
    id_checagem INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_checagem TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resultado VARCHAR(50) NOT NULL,
    observacao TEXT,
    id_parada INTEGER,

    CONSTRAINT fk_checagem_parada
        FOREIGN KEY (id_parada)
        REFERENCES PARADA_MAQUINA(id_parada)
);


-- ============================================================
-- 10. TABELA MOTIVO
-- ============================================================

CREATE TABLE IF NOT EXISTS MOTIVO (
    id_motivo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(150) NOT NULL,
    tipo VARCHAR(50) NOT NULL
);


-- ============================================================
-- 11. TABELA ALTERACAO_FILA
-- ============================================================

CREATE TABLE IF NOT EXISTS ALTERACAO_FILA (
    id_alteracao INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data_alteracao TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    justificativa TEXT NOT NULL,
    ordem_anterior INTEGER NOT NULL,
    nova_ordem INTEGER NOT NULL,
    id_parada INTEGER,
    id_material INTEGER,
    id_motivo INTEGER,

    CONSTRAINT chk_alteracao_ordem_anterior
        CHECK (ordem_anterior > 0),

    CONSTRAINT chk_alteracao_nova_ordem
        CHECK (nova_ordem > 0),

    CONSTRAINT fk_alteracao_parada
        FOREIGN KEY (id_parada)
        REFERENCES PARADA_MAQUINA(id_parada),

    CONSTRAINT fk_alteracao_material
        FOREIGN KEY (id_material)
        REFERENCES MATERIA_PRIMA(id_material),

    CONSTRAINT fk_alteracao_motivo
        FOREIGN KEY (id_motivo)
        REFERENCES MOTIVO(id_motivo)
);


-- ============================================================
-- 12. TABELA OF_MAQUINA
-- ============================================================

CREATE TABLE IF NOT EXISTS OF_MAQUINA (
    id_of INTEGER NOT NULL,
    id_maquina INTEGER NOT NULL,
    ordem_na_fila INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'Aguardando',

    PRIMARY KEY (id_of, id_maquina),

    CONSTRAINT chk_of_maquina_ordem
        CHECK (ordem_na_fila > 0),

    CONSTRAINT fk_of_maquina_of
        FOREIGN KEY (id_of)
        REFERENCES ORDEM_FABRICACAO(id_of)
        ON DELETE CASCADE,

    CONSTRAINT fk_of_maquina_maquina
        FOREIGN KEY (id_maquina)
        REFERENCES MAQUINA(id_maquina)
);


-- ============================================================
-- 13. TABELA OF_COR
-- ============================================================

CREATE TABLE IF NOT EXISTS OF_COR (
    id_of INTEGER NOT NULL,
    id_cor INTEGER NOT NULL,

    PRIMARY KEY (id_of, id_cor),

    CONSTRAINT fk_of_cor_of
        FOREIGN KEY (id_of)
        REFERENCES ORDEM_FABRICACAO(id_of)
        ON DELETE CASCADE,

    CONSTRAINT fk_of_cor_cor
        FOREIGN KEY (id_cor)
        REFERENCES COR(id_cor)
);


-- ============================================================
-- 14. TABELA OF_LOTE
-- ============================================================

CREATE TABLE IF NOT EXISTS OF_LOTE (
    id_of INTEGER NOT NULL,
    id_lote INTEGER NOT NULL,

    PRIMARY KEY (id_of, id_lote),

    CONSTRAINT fk_of_lote_of
        FOREIGN KEY (id_of)
        REFERENCES ORDEM_FABRICACAO(id_of)
        ON DELETE CASCADE,

    CONSTRAINT fk_of_lote_lote
        FOREIGN KEY (id_lote)
        REFERENCES LOTE_PRODUCAO(id_lote)
);


-- ============================================================
-- 15. TABELA LOTE_MATERIAL
-- ============================================================

CREATE TABLE IF NOT EXISTS LOTE_MATERIAL (
    id_lote INTEGER NOT NULL,
    id_material INTEGER NOT NULL,
    quantidade_utilizada DECIMAL(10,2) NOT NULL,

    PRIMARY KEY (id_lote, id_material),

    CONSTRAINT chk_lote_material_quantidade
        CHECK (quantidade_utilizada > 0),

    CONSTRAINT fk_lote_material_lote
        FOREIGN KEY (id_lote)
        REFERENCES LOTE_PRODUCAO(id_lote)
        ON DELETE CASCADE,

    CONSTRAINT fk_lote_material_material
        FOREIGN KEY (id_material)
        REFERENCES MATERIA_PRIMA(id_material)
);


-- ============================================================
-- 16. TABELA CARGA_USUARIO
-- ============================================================

CREATE TABLE IF NOT EXISTS CARGA_USUARIO (
    id_carga INTEGER NOT NULL,
    id_usuario INTEGER NOT NULL,

    PRIMARY KEY (id_carga, id_usuario),

    CONSTRAINT fk_carga_usuario_carga
        FOREIGN KEY (id_carga)
        REFERENCES CARGA(id_carga)
        ON DELETE CASCADE,

    CONSTRAINT fk_carga_usuario_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES USUARIO(id_usuario)
);


-- ============================================================
-- 17. TABELA USUARIO_CHECAGEM
-- ============================================================

CREATE TABLE IF NOT EXISTS USUARIO_CHECAGEM (
    id_usuario INTEGER NOT NULL,
    id_checagem INTEGER NOT NULL,

    PRIMARY KEY (id_usuario, id_checagem),

    CONSTRAINT fk_usuario_checagem_usuario
        FOREIGN KEY (id_usuario)
        REFERENCES USUARIO(id_usuario)
        ON DELETE CASCADE,

    CONSTRAINT fk_usuario_checagem_checagem
        FOREIGN KEY (id_checagem)
        REFERENCES CHECAGEM_QUALIDADE(id_checagem)
        ON DELETE CASCADE
);



-- TESTE 3: consultar OFs com suas cargas

SELECT
    OFAB.id_of,
    OFAB.cliente_destino,
    OFAB.cidade,
    OFAB.data_entrega,
    OFAB.peso,
    C.id_carga,
    C.status AS status_carga
FROM ORDEM_FABRICACAO OFAB
LEFT JOIN CARGA C
    ON OFAB.id_carga = C.id_carga;


-- TESTE 4: consultar a fila das máquinas

SELECT
    OM.id_maquina,
    M.nome_maquina,
    OM.id_of,
    OM.ordem_na_fila,
    OM.status
FROM OF_MAQUINA OM
JOIN MAQUINA M
    ON OM.id_maquina = M.id_maquina
ORDER BY
    OM.id_maquina,
    OM.ordem_na_fila;


-- TESTE 5: consultar OFs e suas cores

SELECT
    OFAB.id_of,
    OFAB.cliente_destino,
    C.nome_cor,
    C.ordem_sequenciamento
FROM OF_COR OC
JOIN ORDEM_FABRICACAO OFAB
    ON OC.id_of = OFAB.id_of
JOIN COR C
    ON OC.id_cor = C.id_cor
ORDER BY
    C.ordem_sequenciamento;


